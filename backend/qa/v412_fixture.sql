CREATE TABLE qa_v412.results(name text PRIMARY KEY, pass boolean NOT NULL, detail jsonb);
CREATE FUNCTION qa_v412.assert(p_name text,p_pass boolean,p_detail jsonb DEFAULT '{}')
RETURNS void LANGUAGE plpgsql AS $f$
BEGIN
 IF p_pass IS DISTINCT FROM true THEN RAISE EXCEPTION 'V412 check failed: %, %',p_name,p_detail;END IF;
 INSERT INTO qa_v412.results VALUES(p_name,true,p_detail);
END $f$;
CREATE FUNCTION qa_v412.expect_error(p_name text,p_sql text,p_code text DEFAULT 'P0001')
RETURNS void LANGUAGE plpgsql AS $f$
DECLARE code text;message text;
BEGIN
 BEGIN EXECUTE p_sql;EXCEPTION WHEN OTHERS THEN code:=SQLSTATE;message:=SQLERRM;END;
 PERFORM qa_v412.assert(p_name,code=p_code,jsonb_build_object('code',code,'message',message));
END $f$;
