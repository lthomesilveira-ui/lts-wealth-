"""Rebuild the reviewed SQL migration from its generic, versioned sections."""
from pathlib import Path
import argparse

ROOT=Path(__file__).resolve().parents[3]
PATCH=ROOT/'backend/patches/v411'
TARGET=ROOT/'supabase/migrations/20261104154908_v411_owner_rsu_cash_policy.sql'
SECTIONS=('preconditions.sql','owner_rsu_cash_policy.sql','consumer_patch.sql','postconditions.sql')

def build():
    return '-- Generated by backend/tools/rsu_policy_v411/build_migration.py.\n'+''.join(
        '\n-- SECTION: '+name+'\n'+(PATCH/name).read_text().rstrip()+'\n' for name in SECTIONS)

if __name__=='__main__':
    parser=argparse.ArgumentParser()
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    content=build()
    if args.check:
        assert TARGET.read_text()==content,'Migration differs from its reviewed sections'
        print('V411 migration source parity: PASS')
    else:
        TARGET.write_text(content)
