#!/usr/bin/env python3
"""Assemble the reviewed generic V412 migration; no database connection."""
from pathlib import Path
import hashlib
import json
import argparse

ROOT = Path(__file__).resolve().parents[3]
PATCH = ROOT / "backend/patches/v412"
ORDER = ["schema.sql", "cache.sql", "base_flow.sql", "source_adapter.sql",
         "calculation.sql", "reference_state.sql", "orchestration.sql", "integration.sql"]
TARGET = ROOT / "supabase/migrations/20261104192749_v412_owner_projection_policy.sql"

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Verify exact generated bytes without writing')
    args = parser.parse_args()
    sections = [(name, (PATCH / name).read_text()) for name in ORDER]
    sql = "-- V412: owner-authorized projection policy; generic code only.\nBEGIN;\n"
    sql += "\n".join("\n-- SOURCE: " + name + "\n" + content for name, content in sections)
    sql += "\nCOMMIT;\n"
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != sql:
            raise SystemExit('V412 migration differs from the reviewed source files')
    else:
        TARGET.write_text(sql)
    print(json.dumps({"pass": True, "check_only": args.check, "migration": str(TARGET.relative_to(ROOT)),
                      "sha256": hashlib.sha256(sql.encode()).hexdigest(),
                      "source_files": ORDER}, sort_keys=True))

if __name__ == "__main__":
    main()
