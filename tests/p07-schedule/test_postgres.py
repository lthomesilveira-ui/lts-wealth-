 def test_concurrent_new_row_edit_prevents_recovery_commit(self):
  self.apply();before_rule=self.rule();writer=connect();worker=connect();result=queue.Queue();thread=None
  try:
   writer.execute('BEGIN');writer.execute('UPDATE financial_events SET amount=amount-1 WHERE id=%s',(F['new'][0]['id'],))
   def recover():
    try:execute_candidate(worker,'recovery');result.put(('committed',None))
    except Exception as error:result.put(('aborted',getattr(error,'sqlstate',type(error).__name__)))
   thread=threading.Thread(target=recover,daemon=True);thread.start()
   # Allow slow thread startup without changing either candidate timeout.
   deadline=time.monotonic()+10;observed=False
   while time.monotonic()<deadline:
    state=self.db.execute('SELECT wait_event_type FROM pg_stat_activity WHERE pid=%s',(worker.info.backend_pid,)).fetchone()
    if state and state[0]=='Lock':observed=True;break
    if not result.empty():break
    time.sleep(.01)
   self.assertTrue(observed,'Recovery did not encounter the held row lock; race not exercised')
   writer.execute('COMMIT');thread.join(5);self.assertFalse(thread.is_alive())
   self.assertEqual(result.get_nowait(),('aborted','40001'))
   self.assertEqual(self.rule(),before_rule)
   self.assertEqual(self.db.execute('SELECT count(*) FROM financial_events WHERE is_suppressed').fetchone()[0],0)
   self.reject('recovery','P07_RECOVERY_CONCURRENT_CHANGE')
  finally:
   writer.execute('ROLLBACK');writer.close()
   if thread is not None:
    thread.join(20)
    if thread.is_alive():
     worker.cancel();thread.join(5)
   worker.close()

