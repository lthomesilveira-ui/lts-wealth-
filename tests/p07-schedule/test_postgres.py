def connect(dbname=None):
 return psycopg.connect(**local_connection_options(),dbname=dbname or DB,autocommit=True)

def candidate(kind):
 text=(P/f'{kind}.review.sql').read_text()
 match=re.search(r'DO \$apply\$.*?END \$apply\$;',text,re.S)
 if not match:raise AssertionError('Expected frozen DO block')
 return match[0]

def execute_candidate(conn,kind,after=None):
 with conn.transaction():
  conn.execute('SET TRANSACTION ISOLATION LEVEL SERIALIZABLE')
  conn.execute("SET LOCAL statement_timeout='15s'")
  conn.execute("SET LOCAL lock_timeout='2s'")
  conn.execute(candidate(kind))
  if after:conn.execute(after)

