"""Fail-closed, local disposable PG17 runner. Default only verifies package hashes.
No installation, cluster creation, network connection, DDL, DML, upload or CI.
"""
import argparse,hashlib,json,os,re,subprocess,tempfile
from pathlib import Path
# Bootstrap integrity uses stdlib only. Never import the adjacent verifier/cache
# before its bytes are checked against the externally pinned manifest.
class VerificationError(ValueError): pass
def strict_load(s):
    def pairs(xs):
        out={}
        for k,v in xs:
            if k in out: raise VerificationError('duplicate JSON key')
            out[k]=v
        return out
    try: return json.loads(s,object_pairs_hook=pairs,parse_constant=lambda x: (_ for _ in ()).throw(VerificationError('invalid JSON constant')))
    except json.JSONDecodeError as e: raise VerificationError('invalid JSON document') from e
ROOT=Path(__file__).parent

def digest(path): return hashlib.sha256(path.read_bytes()).hexdigest()
def package_check(root=ROOT,pin=None,capture=False):
    manifest=root/'PACKAGE_MANIFEST.json'
    manifest_bytes=manifest.read_bytes()
    manifest_hash=hashlib.sha256(manifest_bytes).hexdigest()
    if pin and manifest_hash!=pin: raise VerificationError('manifest pin mismatch')
    m=strict_load(manifest_bytes.decode('utf-8'))
    if set(m)!={'format','files','synthetic_only','pg_executed'} or m['format']!='overlay_pg17_package_v1' or m['synthetic_only'] is not True or m['pg_executed'] is not False:
        raise VerificationError('unexpected package manifest')
    names=[];snapshots={}
    for row in m['files']:
        if set(row)!={'path','sha256'} or not re.fullmatch(r'[A-Za-z0-9_.-]+',row['path']): raise VerificationError('invalid package member')
        names.append(row['path']);p=root/row['path']
        if p.is_symlink() or not p.is_file(): raise VerificationError('invalid package member file')
        data=p.read_bytes()
        if hashlib.sha256(data).hexdigest()!=row['sha256']: raise VerificationError('member hash mismatch: '+row['path'])
        snapshots[row['path']]=data
    if len(set(names))!=len(names): raise VerificationError('duplicate manifest member')
    # No unreviewed sibling scripts/data, except Python-generated bytecode cache.
    present={p.name for p in root.iterdir() if p.name!='__pycache__'}
    if present!=set(names)|{'PACKAGE_MANIFEST.json'}: raise VerificationError('extra or missing package files')
    return (manifest_hash,snapshots) if capture else manifest_hash

def validate_target(socket_dir,database,user,port,ack):
    if not ack: raise VerificationError('explicit disposable local instance acknowledgement required')
    p=Path(socket_dir)
    if not p.is_absolute() or p.is_symlink() or not p.is_dir() or not str(p.resolve()).startswith('/tmp/') or ',' in str(p):
        raise VerificationError('only explicit existing /tmp Unix socket directory accepted')
    if not re.fullmatch(r'overlay_pg17_[a-z0-9_]+',database): raise VerificationError('dedicated synthetic database name required')
    if not re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*',user): raise VerificationError('invalid local role')
    if not 1024<=port<=65535: raise VerificationError('invalid explicit port')
    return p.resolve()

def parse_pg_meta(s):
    m=strict_load(s)
    if not isinstance(m,dict) or set(m)!={'server_version_num','socket_only','read_only'}: raise VerificationError('unexpected PG preflight metadata')
    v=m['server_version_num']
    if type(v) is not int or not 170000<=v<180000 or m['socket_only'] is not True or m['read_only'] is not True:
        raise VerificationError('PG17/socket/read-only gate failed')
    return m

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--execute-local-pg17',action='store_true');ap.add_argument('--ack-disposable',action='store_true')
    ap.add_argument('--expected-manifest-sha256');ap.add_argument('--socket-dir');ap.add_argument('--database');ap.add_argument('--user');ap.add_argument('--port',type=int)
    ap.add_argument('--result-dir',type=Path);ap.add_argument('--psql',default='psql');args=ap.parse_args()
    try:
        pin,snapshots=package_check(pin=args.expected_manifest_sha256,capture=True)
        if not args.execute_local_pg17:
            print(json.dumps({'package_verified':True,'manifest_sha256':pin,'pg_executed':False}));return 0
        if not args.expected_manifest_sha256 or not re.fullmatch('[0-9a-f]{64}',args.expected_manifest_sha256): raise VerificationError('external reviewed manifest pin required')
        if any(x is None for x in (args.socket_dir,args.database,args.user,args.port,args.result_dir)): raise VerificationError('explicit local target and result directory required')
        socket=validate_target(args.socket_dir,args.database,args.user,args.port,args.ack_disposable)
        if args.result_dir.exists(): raise VerificationError('result directory already exists; no overwrite/retry')
        cmd=[args.psql,'-X','-qAt','-w','-v','ON_ERROR_STOP=1','-h',str(socket),'-p',str(args.port),'-U',args.user,'-d',args.database]
        # Strip all inherited libpq env, service/password defaults and startup config.
        with tempfile.TemporaryDirectory(prefix='overlay-runner-home-') as home:
            env={'PATH':os.environ.get('PATH','/usr/bin:/bin'),'LANG':'C.UTF-8','HOME':home,'PGPASSFILE':'/dev/null','PGSERVICEFILE':'/dev/null','PGCONNECT_TIMEOUT':'5','PGAPPNAME':'synthetic_overlay_pg17_gate'}
            body=snapshots['overlay_contract.sql'].decode('utf-8')
            guard="SELECT (current_setting('server_version_num')::integer BETWEEN 170000 AND 179999 AND inet_server_addr() IS NULL AND current_setting('transaction_read_only')='on') AS target_ok\n\\gset\n\\if :target_ok\n\\else\n\\quit 4\n\\endif\n"
            meta_query="SELECT json_build_object('server_version_num',current_setting('server_version_num')::integer,'socket_only',inet_server_addr() IS NULL,'read_only',current_setting('transaction_read_only')='on');\n"
            sql="BEGIN READ ONLY; SET LOCAL statement_timeout='20s'; SET LOCAL lock_timeout='2s'; SET LOCAL timezone='UTC'; SET LOCAL datestyle='ISO,YMD'; SET LOCAL search_path=pg_catalog;\n"+guard+meta_query+body+"\nROLLBACK;\n"
            r=subprocess.run(cmd,env=env,input=sql,text=True,capture_output=True,timeout=30,check=False)
            if r.returncode: raise VerificationError('PG process failed; no output accepted')
            lines=r.stdout.strip().splitlines()
            if len(lines)!=2: raise VerificationError('expected exactly metadata and result from one session')
            meta=parse_pg_meta(lines[0])
            # Load reviewed source bytes directly, ignoring any .pyc cache.
            module={'__name__':'verified_overlay_verifier','__file__':str(ROOT/'verify_results.py')}
            exec(compile(snapshots['verify_results.py'],str(ROOT/'verify_results.py'),'exec'),module)
            outcome=module['verify'](module['strict_load'](lines[1]),module['strict_load'](snapshots['inputs.json'].decode('utf-8')),module['strict_load'](snapshots['expected.json'].decode('utf-8')))
            # A successful receipt is emitted only after exact verification. Logs are synthetic.
            args.result_dir.mkdir(parents=True)
            (args.result_dir/'actual.json').write_text(lines[1]+'\n')
            (args.result_dir/'stderr.txt').write_text(r.stderr)
            (args.result_dir/'receipt.json').write_text(json.dumps({'pg_executed':True,'manifest_sha256':pin,'pg_meta':meta,'verification':outcome},indent=2)+'\n')
            print(json.dumps({'pg_executed':True,'verified':True,'cases':outcome['cases'],'manifest_sha256':pin}));return 0
    except (ValueError,OSError,subprocess.SubprocessError) as e:
        print(json.dumps({'verified':False,'error':str(e),'pg_success_receipt_created':False}));return 1
if __name__=='__main__': raise SystemExit(main())
